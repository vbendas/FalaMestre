/**
 * Hiring and firing, split on the action, because they do not take the same
 * body: a hire names a tier and a firing has nothing to name one for.
 *
 * Taking `tier` as merely optional was how a hire with no tier got through,
 * and the route read the missing value as the top of the three — charging
 * the elite price and handing out an elite coach. A hire has to say which.
 */
export const staffRequestSchema = z.discriminatedUnion('action', [
  z.object({
    action: z.literal('hire'),
    userId: optionalUserIdSchema,
    role: staffRoleSchema,
    tier: z.enum(['rookie', 'professional', 'elite'], {
      error: 'tier must be one of: rookie, professional, elite',
    }),
  }),
  z.object({
    action: z.literal('fire'),
    userId: optionalUserIdSchema,
    role: staffRoleSchema,
  }),
], { error: 'action must be one of: hire, fire' });

